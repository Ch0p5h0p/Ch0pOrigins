package org.Ch0p5h0p.Ch0pOrigins.gui;

public class AbilityDoc {
    private String name;
    private String desc;

    public AbilityDoc(String name, String desc) {
        this.name = name;
        this.desc = desc;
    }

    public String getName() {
        return this.name;
    }

    public String getDesc() {
        return this.desc;
    }
}
